// Turns the BeerJSON copy of the BJCP 2021 guidelines into the compact file the Style Guide loads.
// Run with: npm run build:styles
const fs = require('fs');
const path = require('path');

const SOURCE = path.join(__dirname, '..', 'data', 'bjcp-2021.source.json');
const OUT = path.join(__dirname, '..', 'assets', 'styles-data.js');

// The Argentine and Brazilian entries use Spanish or Portuguese field names; map them to ours.
const FIELDS = {
  overall:    ['overall_impression', 'impresion_general', 'impressao_geral'],
  aroma:      ['aroma'],
  appearance: ['appearance', 'aspecto', 'aparencia'],
  flavor:     ['flavor', 'sabor'],
  mouthfeel:  ['mouthfeel', 'sensacion_en_boca', 'sensacao_de_boca'],
  comments:   ['comments', 'comentarios'],
  history:    ['history', 'historia'],
  ingredients:['ingredients', 'ingredientes'],
  comparison: ['style_comparison', 'comparacoes_de_estilo'],
  examples:   ['examples', 'ejemplos_comerciales', 'exemplos_comerciais'],
  entry:      ['entry_instructions'],
  notes:      ['notes'],
  vitals:     ['vital_statistics'],
};
const STATS = {
  og: 'original_gravity',
  fg: 'final_gravity',
  ibu: 'international_bitterness_units',
  srm: 'color',
  abv: 'alcohol_by_volume',
};

function clean(text) {
  if (typeof text !== 'string') return '';
  // The source drops the space after some commas ("strong,pale"); put it back without touching numbers like 1,000.
  return text.replace(/\s+/g, ' ').replace(/([,;])(?=[A-Za-z])/g, '$1 ').trim();
}

function language(raw) {
  if ('impresion_general' in raw || 'aspecto' in raw) return 'es';
  if ('impressao_geral' in raw || 'aparencia' in raw) return 'pt';
  return 'en';
}

function convert(raw) {
  // Bière de Garde: a conversion glitch split one sentence across "appearance" and a stray "accordingly" key.
  if (raw.accordingly) raw = { ...raw, appearance: `${clean(raw.appearance)} accordingly: ${clean(raw.accordingly)}` };

  const text = {};
  for (const [key, names] of Object.entries(FIELDS)) {
    const value = names.map(n => clean(raw[n])).find(Boolean);
    if (value) text[key] = value;
  }

  let stats = null;
  if (Object.values(STATS).every(k => raw[k])) {
    stats = {};
    for (const [key, field] of Object.entries(STATS)) {
      stats[key] = [raw[field].minimum.value, raw[field].maximum.value];
    }
  }

  const tagSource = raw.tags || raw.marcacoes || '';
  const tags = [...new Set(tagSource.split(',').map(t => t.trim().toLowerCase()).filter(t => /^[a-z-]+$/.test(t)))];

  return {
    id: raw.style_id,
    name: raw.name,
    categoryId: raw.category_id,
    category: raw.category,
    lang: language(raw),
    stats,
    tags,
    types: raw.currently_defined_types ? raw.currently_defined_types.split(',').map(clean) : [],
    text,
  };
}

function sortKey(id) {
  const m = /^(\d+|X)(\w*)$/.exec(id);
  const cat = m[1] === 'X' ? 99 : Number(m[1]);
  return [cat, m[2]];
}

function build() {
  const source = JSON.parse(fs.readFileSync(SOURCE, 'utf8')).beerjson.styles;
  const styles = source.map(convert).sort((a, b) => {
    const [ca, sa] = sortKey(a.id), [cb, sb] = sortKey(b.id);
    return ca - cb || sa.localeCompare(sb, 'en', { numeric: true });
  });

  const categories = [];
  for (const raw of source) {
    const key = raw.category;
    if (categories.some(c => c.name === key)) continue;
    categories.push({ id: raw.category_id, name: key, description: clean(raw.category_description) });
  }
  categories.sort((a, b) => sortKey(a.id + 'A')[0] - sortKey(b.id + 'A')[0]);

  const data = { guide: 'BJCP 2021', categories, styles };
  const banner = '// Generated by tools/build-styles.js from data/bjcp-2021.source.json. Do not edit by hand.\n' +
    '// Style text © Beer Judge Certification Program (BJCP 2021 Style Guidelines); data via BeerJSON (MIT).\n';
  fs.writeFileSync(OUT, `${banner}(typeof window !== 'undefined' ? window : globalThis).BJCP_STYLES = ${JSON.stringify(data)};\n`);
  return data;
}

if (require.main === module) {
  const data = build();
  console.log(`Wrote ${data.styles.length} styles in ${data.categories.length} categories to ${path.relative(process.cwd(), OUT)}`);
}

module.exports = { build, convert };
